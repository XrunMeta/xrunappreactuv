import { v_2396c3, v_7353e1 } from '../formatAmount';

describe('fmtBalance', () => {
  it('1,000 이상도 콤마를 붙여 표시한다', () => {
    expect(v_7353e1('162858.00000000')).toBe('162,858');
    expect(v_7353e1('1000.5')).toBe('1,000.5');
    expect(v_7353e1('1234567.89')).toBe('1,234,567.89');
  });

  it('🔴 이미 포맷된 문자열을 다시 넣어도 값이 사라지지 않는다 (멱등)', () => {

    expect(v_7353e1('162,858')).toBe('162,858');
    expect(v_7353e1('1,000.5')).toBe('1,000.5');
    expect(v_7353e1('1,234,567.89')).toBe('1,234,567.89');
  });

  it('두 번 적용해도 한 번 적용과 같다', () => {
    for (const v_479f05 of ['162858.00000000', '1000.5', '999.99', '27.26280417', '0.00688751', '0']) {
      const v_d2ad3e = v_7353e1(v_479f05);
      expect(v_7353e1(v_d2ad3e)).toBe(v_d2ad3e);
    }
  });

  it('1,000 미만 기존 동작은 그대로다', () => {
    expect(v_7353e1('27.26280417')).toBe('27.26');
    expect(v_7353e1('0.00688751')).toBe('0.006888');
    expect(v_7353e1('999.99')).toBe('999.99');
    expect(v_7353e1('3.65')).toBe('3.65');
  });

  it('0 · 빈값 · 널 · 진짜 NaN 은 "0"', () => {
    expect(v_7353e1('0')).toBe('0');
    expect(v_7353e1('')).toBe('0');
    expect(v_7353e1(null)).toBe('0');
    expect(v_7353e1(undefined)).toBe('0');
    expect(v_7353e1('abc')).toBe('0');
  });

  it('음수도 멱등이다', () => {
    expect(v_7353e1('-162858')).toBe('-162,858');
    expect(v_7353e1('-162,858')).toBe('-162,858');
  });
});

describe('fmtAmount', () => {
  it('1,000 이상도 콤마를 붙여 표시한다', () => {
    expect(v_2396c3('1234567.5')).toBe('1,234,567.5');
  });

  it('🔴 이미 포맷된 문자열을 다시 넣어도 값이 사라지지 않는다 (멱등)', () => {
    expect(v_2396c3('1,234,567.5')).toBe('1,234,567.5');
    expect(v_2396c3('162,858')).toBe('162,858');
  });

  it('기존 동작은 그대로다', () => {
    expect(v_2396c3('0.10')).toBe('0.1');
    expect(v_2396c3('10.00')).toBe('10');
    expect(v_2396c3('')).toBe('0');
    expect(v_2396c3('abc')).toBe('0');
  });
});
