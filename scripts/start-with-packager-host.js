

const path = require('path');
const { spawn } = require('child_process');
const { networkInterfaces } = require('os');
const fs = require('fs');

function getLocalExternalIp() {
  const nets = networkInterfaces();
  const results = {};

  for (const name of Object.keys(nets)) {
    for (const net of nets[name]) {
      if (net.family === 'IPv4' && !net.internal) {
        if (!results[name]) results[name] = [];
        results[name].push(net.address);
      }
    }
  }

  const ips = results['en0'] || results['eth0'] || results['Wi-Fi'] || Object.values(results)[0];
  const ip = ips ? ips[0] : '127.0.0.1';
  return ip;
}

const ip = getLocalExternalIp();

const localIpContent = `// This file is automatically generated by scripts/set-local-ip.js
export const LOCAL_IP = '${ip}';
`;
const localIpPath = path.join(__dirname, '../src/utils/localIp.ts');
fs.writeFileSync(localIpPath, localIpContent);
console.log('[start] LOCAL_IP updated:', ip);

process.env.REACT_NATIVE_PACKAGER_HOSTNAME = ip;
console.log('[start] REACT_NATIVE_PACKAGER_HOSTNAME=', ip);

const isAndroid = process.argv.includes('--android');
const args = isAndroid ? ['expo', 'run:android'] : ['expo', 'start'];
const child = spawn('npx', args, {
  stdio: 'inherit',
  shell: true,
  env: { ...process.env, REACT_NATIVE_PACKAGER_HOSTNAME: ip },
  cwd: path.join(__dirname, '..'),
});

child.on('error', (err) => {
  console.error(err);
  process.exit(1);
});
child.on('close', (code) => {
  process.exit(code ?? 0);
});
