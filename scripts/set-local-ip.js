const fs = require('fs');
const path = require('path');
const { networkInterfaces } = require('os');

function getLocalExternalIp() {
    const nets = networkInterfaces();
    const results = {};

    for (const name of Object.keys(nets)) {
        for (const net of nets[name]) {

            if (net.family === 'IPv4' && !net.internal) {
                if (!results[name]) {
                    results[name] = [];
                }
                results[name].push(net.address);
            }
        }
    }

    const ips = results['en0'] || results['eth0'] || Object.values(results)[0];
    return ips ? ips[0] : '127.0.0.1';
}

const ip = getLocalExternalIp();
const content = `// This file is automatically generated by scripts/set-local-ip.js
export const LOCAL_IP = '${ip}';
`;

const filePath = path.join(__dirname, '../src/utils/localIp.ts');

fs.writeFileSync(filePath, content);
console.log(`Updated localIp.ts with IP: ${ip}`);
